"""Pydantic models and enums for the LLM Wiki module.

This module defines all data types used by the Wiki subsystem:
WikiSummaries, WikiChapterSummaries, status tracking, and
Agent input/output contracts. These are non-DB domain models
used by WikiService and WikiGenerationAgent in the core layer.

See ADR-022 for full architecture context.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel


class WikiSummaryStatus(StrEnum):
    """Tracks the freshness state of a wiki summary.

    Attributes:
        PENDING: Generation queued but not yet complete.
        FRESH: Up to date (all dependencies current).
        STALE: Dependencies changed — refresh needed.
    """

    PENDING = "pending"
    FRESH = "fresh"
    STALE = "stale"


class WikiEntityOutput(BaseModel):
    """Structured output of a WikiGenerationAgent run for an entity summary.

    Generated by the agent when processing a single KB entity.

    Attributes:
        narrative_summary: 2-3 sentence narrative description of the entity.
        role_in_story: Character role or function in the story (1 sentence).
        key_attributes: 3-5 narratively relevant attributes.
        relationships: List of relationships with chapter context.
        character_arc: Character development arc (only for entity_type=character).
    """

    narrative_summary: str
    role_in_story: str | None = None
    key_attributes: list[str]
    relationships: list[dict[str, Any]]
    character_arc: str | None = None


class WikiChapterOutput(BaseModel):
    """Structured output of a WikiGenerationAgent run for a chapter summary.

    Extends the ChapterSummary concept (WRITE-012) with entity tracking.

    Attributes:
        narrative_summary: ~60 token narrative summary of the chapter.
        key_events: Important events that occur in this chapter.
        entities_involved: Entities appearing in the chapter with role/significance.
        themes: Topics and subplots addressed in the chapter.
        emotional_arc: Emotional progression through the chapter.
    """

    narrative_summary: str
    key_events: list[str]
    entities_involved: list[dict[str, Any]]
    themes: list[str]
    emotional_arc: str | None = None


class WikiGenerationDeps(BaseModel):
    """Dependency container for WikiGenerationAgent.

    Provides all context needed to generate a wiki summary for a
    single KB entity or chapter. Passed as ``deps`` to the agent.

    Attributes:
        language: The project language (e.g., "en", "de", "fr").
        genre: The project genre (e.g., "Fantasy", "Sci-Fi").
        entity_type: Type of entity (character, location, faction, etc.).
        entity_name: Name of the entity to summarize.
        entity_body: Raw KB entry body content.
        entity_metadata: Template-specific metadata fields.
        relationships: Known relationships to other entities.
        chapter_context: Chapter content where entity appears.
    """

    language: str
    genre: str
    entity_type: str
    entity_name: str
    entity_body: str
    entity_metadata: dict[str, Any] = {}
    relationships: list[dict[str, Any]] = []
    chapter_context: list[str] = []


class WikiSummaryData(BaseModel):
    """Core domain data for a WikiSummary (non-DB).

    Represents the precomputed narrative summary of a single KB entity.
    This is the domain object used by WikiService and stored/retrieved
    via WikiRepository. Not a SQLAlchemy model — the DB model lives in
    the API layer.

    Attributes:
        entity_id: The KB entity this summary describes.
        novel_id: The parent novel / project.
        narrative_summary: 2-3 sentence narrative description.
        role_in_story: Entity's role or function in the story.
        key_attributes: Important narratively relevant attributes.
        relationships: Relationships to other entities with context.
        chapter_references: Chapters where this entity appears.
        character_arc: Character development arc (characters only).
        depends_on: Dependency snapshot for staleness detection.
        status: Current freshness state.
        version: Incremented on each regeneration.
        content_hash: Hash of the generated content for cache comparison.
    """

    entity_id: str
    novel_id: str
    narrative_summary: str
    role_in_story: str | None = None
    key_attributes: list[str] = []
    relationships: list[dict[str, Any]] = []
    chapter_references: list[str] = []
    character_arc: str | None = None
    depends_on: dict[str, Any] = {}
    status: WikiSummaryStatus = WikiSummaryStatus.PENDING
    version: int = 1
    content_hash: str = ""


class WikiChapterSummaryData(BaseModel):
    """Core domain data for a WikiChapterSummary (non-DB).

    Represents the precomputed narrative summary of a finalized chapter.
    Extends the ChapterSummary concept (WRITE-012) with entity involvement,
    key events, and thematic tracking.

    Attributes:
        chapter_id: The chapter this summary describes.
        narrative_summary: ~60 token narrative summary.
        key_events: Important events in this chapter.
        entities_involved: Entities appearing with role and significance.
        themes: Topics and subplots addressed.
        emotional_arc: Emotional progression through the chapter.
        chapter_content_hash: Hash of chapter content at generation time.
        wiki_prompt_version: Wiki prompt version used for generation.
        status: Current freshness state.
        version: Incremented on each regeneration.
    """

    chapter_id: str
    narrative_summary: str
    key_events: list[str] = []
    entities_involved: list[dict[str, Any]] = []
    themes: list[str] = []
    emotional_arc: str | None = None
    chapter_content_hash: str = ""
    wiki_prompt_version: str = ""
    status: WikiSummaryStatus = WikiSummaryStatus.PENDING
    version: int = 1
