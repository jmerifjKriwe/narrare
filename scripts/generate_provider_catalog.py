#!/usr/bin/env python3
"""Render the provider-catalog artifacts from ``catalog.yaml`` (ADR-099).

``catalog.yaml`` is the single source of truth for *which providers Narrare
supports and how they are spelled*. This generator turns it into checked-in
code, so no surface can restate the provider set by hand:

* default mode writes the generated Python module (``PY_OUTPUT``) and the
  generated TypeScript module (``TS_OUTPUT``);
* ``--check`` renders both in memory, compares **bytes** against the committed
  artifacts (ADR-099 §6) and also runs the parity gate
  (:func:`scripts.provider_catalog_parity.check_parity`) plus the fetcher
  invariant (:func:`check_fetchers`): the hand-written Core surfaces are
  **parsed** with :mod:`ast` (never imported); every missing or disagreeing fact
  is printed as ``<surface>: <detail>`` and exits ``1``.

The catalog is read at **build time only** — nothing loads it at runtime.

Usage::

    uv run --all-packages python scripts/generate_provider_catalog.py
    uv run --all-packages python scripts/generate_provider_catalog.py --check
"""

from __future__ import annotations

import argparse
import ast
import difflib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

# The parity gate lives in a sibling module. Insert the repo root so
# ``scripts.provider_catalog_parity`` resolves both when this file is executed
# as a script (``python scripts/generate_provider_catalog.py``, where
# ``sys.path[0]`` is ``scripts/``) and when it is imported as
# ``scripts.generate_provider_catalog`` (tests, where only the repo root is on
# ``sys.path``). Same bootstrap as ``scripts/check_adoption.py``.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import yaml
from scripts.provider_catalog_parity import PRICING_KEYS, ParityViolation, check_parity

REPO_ROOT = Path(__file__).resolve().parent.parent

_PACKAGES_DIR = REPO_ROOT / "packages"
_PROVIDERS_DIR = _PACKAGES_DIR / "core" / "narrare_core" / "llm" / "_providers"

CATALOG_PATH = _PROVIDERS_DIR / "catalog.yaml"
"""The authored SSOT: one ordered entry per provider."""

PY_OUTPUT = _PROVIDERS_DIR / "catalog_generated.py"
"""Generated artifact checked in beside the catalog."""

TS_OUTPUT = _PACKAGES_DIR / "web" / "lib" / "providers.generated.ts"
"""Generated TypeScript artifact; biome-clean as rendered (never post-fixed)."""

_MODEL_LISTING = Path("packages/core/narrare_core/llm/model_listing.py")
"""The provider catalog adapter; ``ModelCatalogClient`` holds the ``_fetch_*`` methods."""

_FIELD_NAMES: frozenset[str] = frozenset(
    {
        "id",
        "label_key",
        "api_key_env",
        "settings_field",
        "pydantic_ai_extra",
        "listing_strategy",
        "pricing_default",
        "cache_policy",
        "fallback_models",
        "settings_editable",
        "requires_endpoint_selector",
    }
)

# A leading letter is required so the upper-cased enum member
# (``_member_name``) is always a valid Python identifier: ``3gpt`` would have
# rendered ``3GPT = ...``, a module that does not parse, and no render-to-render
# round-trip test could see it.
_ID_PATTERN = re.compile(r"[a-z][a-z0-9_]*")

# Closed literal sets (ADR-099 §2): one pydantic-ai integration per provider
# name, and the caching behaviours ``cache_settings.py`` implements. The seven
# ``pydantic_ai_extra`` values are deliberately *restated* here, not derived from
# the catalog: they are pydantic-ai's own integration names, an external closed
# set (ADR-099 §2 marks the field "Closed literal set"), so they are not a missed
# derivation. ``_parse_provider`` validates every catalog entry against this set,
# and a catalog entry naming a new integration must add it here first.
_PYDANTIC_AI_EXTRAS: frozenset[str] = frozenset(
    {"anthropic", "openai", "google", "groq", "ollama", "openrouter", "zai"}
)
_CACHE_POLICIES: frozenset[str] = frozenset({"anthropic_cache_control", "automatic", "none"})

_HEADER = "# AUTO-GENERATED by scripts/generate_provider_catalog.py — DO NOT EDIT"
_TS_HEADER = "// AUTO-GENERATED by scripts/generate_provider_catalog.py — DO NOT EDIT"


@dataclass(frozen=True)
class ProviderSpec:
    """One validated catalog entry — the contract every rendered artifact uses."""

    id: str
    label_key: str
    api_key_env: str | None
    settings_field: str | None
    pydantic_ai_extra: str
    listing_strategy: str
    pricing_default: dict[str, float]
    cache_policy: str
    fallback_models: tuple[str, ...]
    settings_editable: bool
    requires_endpoint_selector: bool


def _error(provider: str, field: str, detail: str) -> ValueError:
    """Build the uniform validation error naming the provider and the field."""
    return ValueError(f"provider {provider!r}: field {field!r}: {detail}")


def _require_str(raw: dict[str, Any], field: str, provider: str) -> str:
    value = raw[field]
    if not isinstance(value, str) or not value:
        raise _error(provider, field, f"expected a non-empty string, got {value!r}")
    return value


def _require_optional_str(raw: dict[str, Any], field: str, provider: str) -> str | None:
    value = raw[field]
    if value is None:
        return None
    if not isinstance(value, str) or not value:
        raise _error(provider, field, f"expected a non-empty string or null, got {value!r}")
    return value


def _require_bool(raw: dict[str, Any], field: str, provider: str) -> bool:
    value = raw[field]
    if not isinstance(value, bool):
        raise _error(provider, field, f"expected a boolean, got {value!r}")
    return value


def _require_member(raw: dict[str, Any], field: str, provider: str, allowed: frozenset[str]) -> str:
    value = _require_str(raw, field, provider)
    if value not in allowed:
        raise _error(provider, field, f"{value!r} is not one of {sorted(allowed)}")
    return value


def _require_pricing(raw: dict[str, Any], provider: str) -> dict[str, float]:
    value: Any = raw["pricing_default"]
    if not isinstance(value, dict):
        raise _error(provider, "pricing_default", f"expected a mapping, got {value!r}")
    rates = cast("dict[str, Any]", value)
    pricing: dict[str, float] = {}
    for key in PRICING_KEYS:
        amount = rates.get(key)
        if isinstance(amount, bool) or not isinstance(amount, (int, float)):
            raise _error(provider, "pricing_default", f"{key!r} must be a number, got {amount!r}")
        pricing[key] = float(amount)
    unknown = sorted(set(rates) - set(PRICING_KEYS))
    if unknown:
        raise _error(provider, "pricing_default", f"unknown rate {unknown[0]!r}")
    return pricing


def _require_model_ids(raw: dict[str, Any], provider: str) -> tuple[str, ...]:
    value: Any = raw["fallback_models"]
    if not isinstance(value, list):
        raise _error(provider, "fallback_models", f"expected a list, got {value!r}")
    model_ids = cast("list[Any]", value)
    if not model_ids:
        raise _error(provider, "fallback_models", "must list at least one fallback model")
    for model_id in model_ids:
        if not isinstance(model_id, str) or not model_id:
            raise _error(
                provider, "fallback_models", f"expected non-empty model IDs, got {model_id!r}"
            )
    return tuple(cast("list[str]", model_ids))


def _validate_field_set(raw: dict[str, Any], provider: str) -> None:
    unknown = sorted(set(raw) - _FIELD_NAMES)
    if unknown:
        raise _error(provider, unknown[0], "unknown field")
    missing = sorted(_FIELD_NAMES - set(raw))
    if missing:
        raise _error(provider, missing[0], "missing field")


def _parse_provider(entry: object, *, index: int) -> ProviderSpec:
    """Validate one raw catalog entry and build its :class:`ProviderSpec`."""
    if not isinstance(entry, dict):
        raise ValueError(f"providers[{index}]: expected a mapping, got {entry!r}")
    raw = cast("dict[str, Any]", entry)

    raw_id = raw.get("id")
    provider = raw_id if isinstance(raw_id, str) else f"providers[{index}]"
    _validate_field_set(raw, provider)

    provider_id = _require_str(raw, "id", provider)
    if _ID_PATTERN.fullmatch(provider_id) is None:
        raise _error(provider, "id", f"{provider_id!r} must match {_ID_PATTERN.pattern!r}")
    # Defense in depth: under ``_ID_PATTERN`` (a leading ASCII letter, then
    # letters/digits/underscores) upper-casing always yields a valid Python
    # identifier, so this branch is unreachable today. It is kept so a future
    # relaxation of the pattern cannot emit a module that fails to parse.
    if not _member_name(provider_id).isidentifier():
        raise _error(
            provider,
            "id",
            f"{provider_id!r} must upper-case to a valid Python identifier "
            f"(got {_member_name(provider_id)!r})",
        )

    return ProviderSpec(
        id=provider_id,
        label_key=_require_str(raw, "label_key", provider),
        api_key_env=_require_optional_str(raw, "api_key_env", provider),
        settings_field=_require_optional_str(raw, "settings_field", provider),
        pydantic_ai_extra=_require_member(raw, "pydantic_ai_extra", provider, _PYDANTIC_AI_EXTRAS),
        listing_strategy=_require_str(raw, "listing_strategy", provider),
        pricing_default=_require_pricing(raw, provider),
        cache_policy=_require_member(raw, "cache_policy", provider, _CACHE_POLICIES),
        fallback_models=_require_model_ids(raw, provider),
        settings_editable=_require_bool(raw, "settings_editable", provider),
        requires_endpoint_selector=_require_bool(raw, "requires_endpoint_selector", provider),
    )


def load_catalog(path: Path) -> list[ProviderSpec]:
    """Load and validate the catalog at ``path``, preserving canonical order.

    Raises:
        ValueError: A malformed document, an unknown or missing per-provider
            field (the message names the provider and the field), a duplicate
            ``id``, or an ``id`` that is not ``[a-z][a-z0-9_]*`` (the leading
            letter keeps the upper-cased enum member a valid identifier).
    """
    raw: Any = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError(f"{path}: expected a mapping with a 'providers' key")
    entries: Any = cast("dict[str, Any]", raw).get("providers")
    if not isinstance(entries, list):
        raise ValueError(f"{path}: 'providers' must be a list")
    if not entries:
        # An empty list would render ``class AIProvider(StrEnum):`` with no
        # members (a module that does not parse) on both sides, so the
        # generate -> --check round trip would still "match".
        raise ValueError(f"{path}: 'providers' must list at least one provider")

    specs: list[ProviderSpec] = []
    seen: set[str] = set()
    for index, entry in enumerate(cast("list[Any]", entries)):
        spec = _parse_provider(entry, index=index)
        if spec.id in seen:
            raise _error(spec.id, "id", "duplicate provider id")
        seen.add(spec.id)
        specs.append(spec)
    return specs


def _member_name(provider_id: str) -> str:
    """The enum member name for a provider id (the id upper-cased)."""
    return provider_id.upper()


def _string_literal(value: str) -> str:
    """A double-quoted source literal for ``value``, escaped for Python and TS.

    ``json.dumps`` produces a valid string literal in both target languages
    (quotes, backslashes and control characters escaped), so a hostile catalog
    string can never emit broken source that the render-to-render round-trip
    test would be blind to.
    """
    return json.dumps(value)


def render_python(specs: list[ProviderSpec]) -> str:
    """Render the generated Python module for ``specs`` (canonical order).

    The output is ruff-format clean by construction and carries no type
    suppressions: the class-syntax ``StrEnum`` is the only representation that
    survives pyright strict (ADR-099 §Rationale).
    """
    lines = [
        _HEADER,
        "# Source: packages/core/narrare_core/llm/_providers/catalog.yaml (ADR-099).",
        "# Regenerate: uv run --all-packages python scripts/generate_provider_catalog.py",
        '"""Canonical provider set derived from the provider catalog SSOT (ADR-099)."""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import StrEnum",
        "",
        '__all__ = ["PROVIDER_IDS", "PROVIDER_LABEL_KEYS", "AIProvider"]',
        "",
        "",
        "# Member order matches the catalog. No class docstring on purpose: pydantic",
        "# renders a class docstring as the JSON-schema `description` of every",
        "# component that references the enum, so a docstring here would silently",
        "# change the public OpenAPI contract when apps/api re-exports it (T2/ADR-099).",
        "class AIProvider(StrEnum):",
    ]
    lines += [f"    {_member_name(spec.id)} = {_string_literal(spec.id)}" for spec in specs]
    lines += ["", "", "PROVIDER_IDS: tuple[str, ...] = ("]
    lines += [f"    {_string_literal(spec.id)}," for spec in specs]
    lines += [")", "", "", "PROVIDER_LABEL_KEYS: dict[AIProvider, str] = {"]
    lines += [
        f"    AIProvider.{_member_name(spec.id)}: {_string_literal(spec.label_key)},"
        for spec in specs
    ]
    lines += ["}", ""]
    return "\n".join(lines)


def render_typescript(specs: list[ProviderSpec]) -> str:
    """Render the generated TypeScript module for ``specs`` (canonical order).

    The output is **biome-clean by construction**: ``biome check`` on the
    committed artifact must pass unchanged, so the template emits the union with
    a two-space-indented continuation, the ids as a ``const`` tuple narrowed by
    ``satisfies``, and the label keys as a record literal. Labels stay fully
    qualified i18n keys (``settings-ai.providers.<id>``) — never a display
    string (RULE-16), so no human-readable label appears in the module.
    """
    lines = [
        _TS_HEADER,
        "// Source: packages/core/narrare_core/llm/_providers/catalog.yaml (ADR-099).",
        "// Regenerate: uv run --all-packages python scripts/generate_provider_catalog.py",
        "",
        "export type AIProvider =",
    ]
    lines += [f"  | {_string_literal(spec.id)}" for spec in specs]
    lines[-1] += ";"
    lines += ["", "export const PROVIDER_IDS = ["]
    lines += [f"  {_string_literal(spec.id)}," for spec in specs]
    lines += [
        "] as const satisfies readonly AIProvider[];",
        "",
        "export const PROVIDER_LABEL_KEYS: Record<AIProvider, string> = {",
    ]
    lines += [f"  {spec.id}: {_string_literal(spec.label_key)}," for spec in specs]
    lines += ["};", ""]
    return "\n".join(lines)


def _display(path: Path) -> str:
    """Repo-relative display path — falls back to the absolute path."""
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def check_fetchers(specs: list[ProviderSpec], repo_root: Path) -> list[ParityViolation]:
    """Every catalog ``listing_strategy`` names a ``ModelCatalogClient._fetch_*``.

    Only method names are read (with :mod:`ast`, never an import), so a fetcher
    may change its body freely; the name is the contract (ADR-099 point 7). An
    absent class or method is a violation, never a silent pass.
    """
    fm = "fetch.methods"
    module = ast.parse((repo_root / _MODEL_LISTING).read_text(encoding="utf-8"))
    client = next(
        (
            node
            for node in module.body
            if isinstance(node, ast.ClassDef) and node.name == "ModelCatalogClient"
        ),
        None,
    )
    if client is None:
        return [ParityViolation(fm, f"ModelCatalogClient is missing from {_MODEL_LISTING}")]
    methods = {
        statement.name
        for statement in client.body
        if isinstance(statement, ast.FunctionDef | ast.AsyncFunctionDef)
    }
    return [
        ParityViolation(
            fm,
            f"{spec.id}: listing_strategy {spec.listing_strategy!r} has no "
            f"_fetch_{spec.listing_strategy} method",
        )
        for spec in specs
        if f"_fetch_{spec.listing_strategy}" not in methods
    ]


def _check(specs: list[ProviderSpec], repo_root: Path) -> int:
    """Verify the generated artifacts (bytes, ADR-099 §6) and the surfaces.

    Returns 0 only when both artifacts match byte-for-byte — a decoded-text
    comparison would be blind to newline drift — and every parity violation,
    including the fetcher invariant, is silent.
    """
    rendered_python = render_python(specs)
    rendered_typescript = render_typescript(specs)

    artifacts = ((PY_OUTPUT, rendered_python), (TS_OUTPUT, rendered_typescript))
    drifted = False
    for path, rendered in artifacts:
        committed_bytes = path.read_bytes()
        if committed_bytes == rendered.encode("utf-8"):
            print(f"provider catalog check: {_display(path)} is up to date")
            continue

        drifted = True
        diff = difflib.unified_diff(
            committed_bytes.decode("utf-8").splitlines(keepends=True),
            rendered.splitlines(keepends=True),
            fromfile=f"{_display(path)} (committed)",
            tofile=f"{_display(path)} (fresh render)",
        )
        sys.stdout.writelines(diff)
        print(
            f"\nprovider catalog check FAILED: {_display(path)} is stale — "
            "regenerate with `uv run --all-packages python scripts/generate_provider_catalog.py`"
        )

    violations = sorted(
        [*check_parity(specs, repo_root), *check_fetchers(specs, repo_root)],
        key=lambda violation: (violation.surface, violation.detail),
    )
    for violation in violations:
        print(f"{violation.surface}: {violation.detail}")

    return 1 if drifted or violations else 0


def main(argv: list[str] | None = None) -> int:
    """Write the generated artifacts, or verify them in ``--check`` mode."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "render in memory, compare the committed artifacts byte-for-byte, and check the "
            "parity surfaces instead of writing"
        ),
    )
    args = parser.parse_args(argv)

    specs = load_catalog(CATALOG_PATH)
    if args.check:
        return _check(specs, REPO_ROOT)

    PY_OUTPUT.write_text(render_python(specs), encoding="utf-8", newline="\n")
    TS_OUTPUT.write_text(render_typescript(specs), encoding="utf-8", newline="\n")
    print(f"wrote {_display(PY_OUTPUT)}")
    print(f"wrote {_display(TS_OUTPUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
