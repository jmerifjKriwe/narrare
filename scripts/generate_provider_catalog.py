#!/usr/bin/env python3
"""Render the provider-catalog artifacts from ``catalog.yaml`` (ADR-099).

``catalog.yaml`` is the single source of truth for *which providers Narrare
supports and how they are spelled*. This generator turns it into checked-in
code, so no surface can restate the provider set by hand:

* default mode writes the generated Python module (``PY_OUTPUT``);
* ``--check`` renders in memory, compares byte-for-byte against the committed
  artifact and exits ``1`` with a unified diff on drift.

The catalog is read at **build time only** — nothing loads it at runtime.

Usage::

    uv run --all-packages python scripts/generate_provider_catalog.py
    uv run --all-packages python scripts/generate_provider_catalog.py --check
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent

_PACKAGES_DIR = REPO_ROOT / "packages"
_PROVIDERS_DIR = _PACKAGES_DIR / "core" / "narrare_core" / "llm" / "_providers"

CATALOG_PATH = _PROVIDERS_DIR / "catalog.yaml"
"""The authored SSOT: one ordered entry per provider."""

PY_OUTPUT = _PROVIDERS_DIR / "catalog_generated.py"
"""Generated artifact checked in beside the catalog."""

TS_OUTPUT = _PACKAGES_DIR / "web" / "lib" / "providers.generated.ts"
"""Generated TypeScript artifact (rendered by a later task of this wave)."""

_FIELD_NAMES: frozenset[str] = frozenset(
    {
        "id",
        "label_key",
        "api_key_env",
        "settings_field",
        "pydantic_ai_extra",
        "listing_strategy",
        "pricing_default",
        "cache_policy",
        "fallback_models",
        "settings_editable",
        "requires_endpoint_selector",
    }
)

_ID_PATTERN = re.compile(r"[a-z0-9_]+")
_PRICING_KEYS: tuple[str, ...] = ("input", "output")

# Closed literal sets (ADR-099 §2): one pydantic-ai integration per provider
# name, and the caching behaviours ``cache_settings.py`` implements.
_PYDANTIC_AI_EXTRAS: frozenset[str] = frozenset(
    {"anthropic", "openai", "google", "groq", "ollama", "openrouter", "zai"}
)
_CACHE_POLICIES: frozenset[str] = frozenset({"anthropic_cache_control", "automatic", "none"})

_HEADER = "# AUTO-GENERATED by scripts/generate_provider_catalog.py — DO NOT EDIT"


@dataclass(frozen=True)
class ProviderSpec:
    """One validated catalog entry — the contract every rendered artifact uses."""

    id: str
    label_key: str
    api_key_env: str | None
    settings_field: str | None
    pydantic_ai_extra: str
    listing_strategy: str
    pricing_default: dict[str, float]
    cache_policy: str
    fallback_models: tuple[str, ...]
    settings_editable: bool
    requires_endpoint_selector: bool


def _error(provider: str, field: str, detail: str) -> ValueError:
    """Build the uniform validation error naming the provider and the field."""
    return ValueError(f"provider {provider!r}: field {field!r}: {detail}")


def _require_str(raw: dict[str, Any], field: str, provider: str) -> str:
    value = raw[field]
    if not isinstance(value, str) or not value:
        raise _error(provider, field, f"expected a non-empty string, got {value!r}")
    return value


def _require_optional_str(raw: dict[str, Any], field: str, provider: str) -> str | None:
    value = raw[field]
    if value is None:
        return None
    if not isinstance(value, str) or not value:
        raise _error(provider, field, f"expected a non-empty string or null, got {value!r}")
    return value


def _require_bool(raw: dict[str, Any], field: str, provider: str) -> bool:
    value = raw[field]
    if not isinstance(value, bool):
        raise _error(provider, field, f"expected a boolean, got {value!r}")
    return value


def _require_member(raw: dict[str, Any], field: str, provider: str, allowed: frozenset[str]) -> str:
    value = _require_str(raw, field, provider)
    if value not in allowed:
        raise _error(provider, field, f"{value!r} is not one of {sorted(allowed)}")
    return value


def _require_pricing(raw: dict[str, Any], provider: str) -> dict[str, float]:
    value: Any = raw["pricing_default"]
    if not isinstance(value, dict):
        raise _error(provider, "pricing_default", f"expected a mapping, got {value!r}")
    rates = cast("dict[str, Any]", value)
    pricing: dict[str, float] = {}
    for key in _PRICING_KEYS:
        amount = rates.get(key)
        if isinstance(amount, bool) or not isinstance(amount, (int, float)):
            raise _error(provider, "pricing_default", f"{key!r} must be a number, got {amount!r}")
        pricing[key] = float(amount)
    unknown = sorted(set(rates) - set(_PRICING_KEYS))
    if unknown:
        raise _error(provider, "pricing_default", f"unknown rate {unknown[0]!r}")
    return pricing


def _require_model_ids(raw: dict[str, Any], provider: str) -> tuple[str, ...]:
    value: Any = raw["fallback_models"]
    if not isinstance(value, list):
        raise _error(provider, "fallback_models", f"expected a list, got {value!r}")
    model_ids = cast("list[Any]", value)
    if not model_ids:
        raise _error(provider, "fallback_models", "must list at least one fallback model")
    for model_id in model_ids:
        if not isinstance(model_id, str) or not model_id:
            raise _error(
                provider, "fallback_models", f"expected non-empty model IDs, got {model_id!r}"
            )
    return tuple(cast("list[str]", model_ids))


def _validate_field_set(raw: dict[str, Any], provider: str) -> None:
    unknown = sorted(set(raw) - _FIELD_NAMES)
    if unknown:
        raise _error(provider, unknown[0], "unknown field")
    missing = sorted(_FIELD_NAMES - set(raw))
    if missing:
        raise _error(provider, missing[0], "missing field")


def _parse_provider(entry: object, *, index: int) -> ProviderSpec:
    """Validate one raw catalog entry and build its :class:`ProviderSpec`."""
    if not isinstance(entry, dict):
        raise ValueError(f"providers[{index}]: expected a mapping, got {entry!r}")
    raw = cast("dict[str, Any]", entry)

    raw_id = raw.get("id")
    provider = raw_id if isinstance(raw_id, str) else f"providers[{index}]"
    _validate_field_set(raw, provider)

    provider_id = _require_str(raw, "id", provider)
    if _ID_PATTERN.fullmatch(provider_id) is None:
        raise _error(provider, "id", f"{provider_id!r} must match {_ID_PATTERN.pattern!r}")

    return ProviderSpec(
        id=provider_id,
        label_key=_require_str(raw, "label_key", provider),
        api_key_env=_require_optional_str(raw, "api_key_env", provider),
        settings_field=_require_optional_str(raw, "settings_field", provider),
        pydantic_ai_extra=_require_member(raw, "pydantic_ai_extra", provider, _PYDANTIC_AI_EXTRAS),
        listing_strategy=_require_str(raw, "listing_strategy", provider),
        pricing_default=_require_pricing(raw, provider),
        cache_policy=_require_member(raw, "cache_policy", provider, _CACHE_POLICIES),
        fallback_models=_require_model_ids(raw, provider),
        settings_editable=_require_bool(raw, "settings_editable", provider),
        requires_endpoint_selector=_require_bool(raw, "requires_endpoint_selector", provider),
    )


def load_catalog(path: Path) -> list[ProviderSpec]:
    """Load and validate the catalog at ``path``, preserving canonical order.

    Raises:
        ValueError: A malformed document, an unknown or missing per-provider
            field (the message names the provider and the field), a duplicate
            ``id``, or an ``id`` outside ``[a-z0-9_]+``.
    """
    raw: Any = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError(f"{path}: expected a mapping with a 'providers' key")
    entries: Any = cast("dict[str, Any]", raw).get("providers")
    if not isinstance(entries, list):
        raise ValueError(f"{path}: 'providers' must be a list")

    specs: list[ProviderSpec] = []
    seen: set[str] = set()
    for index, entry in enumerate(cast("list[Any]", entries)):
        spec = _parse_provider(entry, index=index)
        if spec.id in seen:
            raise _error(spec.id, "id", "duplicate provider id")
        seen.add(spec.id)
        specs.append(spec)
    return specs


def _member_name(provider_id: str) -> str:
    """The enum member name for a provider id (the id upper-cased)."""
    return provider_id.upper()


def render_python(specs: list[ProviderSpec]) -> str:
    """Render the generated Python module for ``specs`` (canonical order).

    The output is ruff-format clean by construction and carries no type
    suppressions: the class-syntax ``StrEnum`` is the only representation that
    survives pyright strict (ADR-099 §Rationale).
    """
    lines = [
        _HEADER,
        "# Source: packages/core/narrare_core/llm/_providers/catalog.yaml (ADR-099).",
        "# Regenerate: uv run --all-packages python scripts/generate_provider_catalog.py",
        '"""Canonical provider set derived from the provider catalog SSOT (ADR-099)."""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import StrEnum",
        "",
        '__all__ = ["PROVIDER_IDS", "PROVIDER_LABEL_KEYS", "AIProvider"]',
        "",
        "",
        "class AIProvider(StrEnum):",
        '    """Provider identifiers; the order matches the catalog."""',
        "",
    ]
    lines += [f'    {_member_name(spec.id)} = "{spec.id}"' for spec in specs]
    lines += ["", "", "PROVIDER_IDS: tuple[str, ...] = ("]
    lines += [f'    "{spec.id}",' for spec in specs]
    lines += [")", "", "", "PROVIDER_LABEL_KEYS: dict[AIProvider, str] = {"]
    lines += [f'    AIProvider.{_member_name(spec.id)}: "{spec.label_key}",' for spec in specs]
    lines += ["}", ""]
    return "\n".join(lines)


def _display(path: Path) -> str:
    """Repo-relative display path — falls back to the absolute path."""
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _check(rendered: str) -> int:
    """Compare ``rendered`` with the committed artifact; ``0`` when identical."""
    committed = PY_OUTPUT.read_text(encoding="utf-8")
    if committed == rendered:
        print(f"provider catalog check: {PY_OUTPUT.name} is up to date")
        return 0

    diff = difflib.unified_diff(
        committed.splitlines(keepends=True),
        rendered.splitlines(keepends=True),
        fromfile=f"{PY_OUTPUT.name} (committed)",
        tofile=f"{PY_OUTPUT.name} (fresh render)",
    )
    sys.stdout.writelines(diff)
    print(
        f"\nprovider catalog check FAILED: {_display(PY_OUTPUT)} is stale — "
        "regenerate with `uv run --all-packages python scripts/generate_provider_catalog.py`"
    )
    return 1


def main(argv: list[str] | None = None) -> int:
    """Write the generated artifact, or verify it in ``--check`` mode."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="render in memory and compare with the committed artifact instead of writing",
    )
    args = parser.parse_args(argv)

    rendered = render_python(load_catalog(CATALOG_PATH))
    if args.check:
        return _check(rendered)

    PY_OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {_display(PY_OUTPUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
