"""Output formatters for the system health report.

Extracted from check_system_health.py for RULE-04 compliance.
"""

from __future__ import annotations

import json

from scripts.health_types import (
    DEGRADED_THRESHOLD,
    HEALTHY_THRESHOLD,
    HealthReport,
)

_STATUS_ICON = {"HEALTHY": "🟢", "DEGRADED": "🟡", "CRITICAL": "🔴"}


def format_human(report: HealthReport) -> str:
    """Format the health report as human-readable text."""
    lines: list[str] = []
    icon = _STATUS_ICON.get(report.status, "")
    lines.append(f"\nSystem Health Score: {report.score:.2f} {report.status} {icon}\n")
    lines.append(f"{'Gate':<25} {'Weight':>7} {'Score':>7}  Details")
    lines.append("-" * 75)

    for gate in report.gates:
        gate_icon = (
            "✅"
            if gate.score >= HEALTHY_THRESHOLD
            else ("⚠️" if gate.score >= DEGRADED_THRESHOLD else "❌")
        )
        lines.append(
            f"  {gate.name:<23} {gate.weight:>6.0%}  {gate.score:>6.2f}  {gate_icon} {gate.details}"
        )

    lines.append("-" * 75)
    lines.append(f"  {'TOTAL':<23} {'1.00':>7}  {report.score:>6.2f}  {icon} {report.status}")
    lines.append("")

    if report.status == "DEGRADED":
        lines.append("⚠️  System health is DEGRADED — review gate details above.")
    elif report.status == "CRITICAL":
        lines.append("❌ System health is CRITICAL — CI will fail.")

    return "\n".join(lines)


def format_json(report: HealthReport) -> str:
    """Format the health report as JSON."""
    data = {
        "score": report.score,
        "status": report.status,
        "thresholds": {
            "healthy": HEALTHY_THRESHOLD,
            "degraded": DEGRADED_THRESHOLD,
        },
        "gates": [
            {
                "name": gate.name,
                "weight": gate.weight,
                "score": gate.score,
                "details": gate.details,
            }
            for gate in report.gates
        ],
    }
    return json.dumps(data, indent=2, ensure_ascii=False)


def format_badge_markdown(report: HealthReport) -> str:
    """Format a Markdown badge file for the system health status."""
    color_map = {"HEALTHY": "brightgreen", "DEGRADED": "yellow", "CRITICAL": "red"}
    color = color_map.get(report.status, "lightgrey")
    pct = int(report.score * 100)
    badge_url = f"https://img.shields.io/badge/System%20Health-{pct}%25-{color}.svg"

    lines = [
        "<!-- System Health Badge - auto-generated by scripts/check_system_health.py -->",
        f"[![System Health]({badge_url})](#system-health)",
        "",
        "## System Health",
        "",
        f"**Score:** {report.score:.2f}  ",
        f"**Status:** {report.status}  ",
        "**Updated:** _(run `just check-health` to update)_  ",
        "",
        "### Gate Breakdown",
        "",
        "| Gate | Weight | Score | Status |",
        "|------|--------|-------|--------|",
    ]
    for gate in report.gates:
        icon = (
            "✅"
            if gate.score >= HEALTHY_THRESHOLD
            else ("⚠️" if gate.score >= DEGRADED_THRESHOLD else "❌")
        )
        lines.append(f"| {gate.name} | {gate.weight:.0%} | {gate.score:.2f} | {icon} |")
    lines.append("")
    return "\n".join(lines)
