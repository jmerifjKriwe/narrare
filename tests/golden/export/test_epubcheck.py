class TestEpubcheckGate:
    """The headline gate: the rendered EPUB validates clean against EPUBCheck.

    CI-only: EPUBCheck is a Java tool (the ``epubcheck`` launcher execs
    ``java -jar``), so the test below additionally skips when ``epubcheck`` or
    ``java`` is absent. The CI integration job installs both (EPUBCheck via
    ``INSTALL_EPUBCHECK=1``; Java ships on the ubuntu runner image). Local dev
    without a JVM still gets the full structural guarantee from the other
    classes in this module.
    """

    @pytest.mark.skipif(
        shutil.which("epubcheck") is None or shutil.which("java") is None,
        reason="epubcheck + java(JRE) not installed — W3C EPUBCheck is "
        "CI-only (integration job: INSTALL_EPUBCHECK=1 + runner JRE)",
    )
    @pytest.mark.asyncio
    async def test_rendered_epub_passes_epubcheck(self) -> None:
        artifact = await PandocEpubRenderer().render(
            _normalized(), ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            result = _run_epubcheck(artifact.path)
            assert result.returncode == 0, (
                f"EPUBCheck reported validation errors:\n"
                f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
            )
        finally:
            artifact.path.unlink(missing_ok=True)

    @pytest.mark.skipif(
        shutil.which("epubcheck") is None or shutil.which("java") is None,
        reason="epubcheck + java(JRE) not installed — W3C EPUBCheck is "
        "CI-only (integration job: INSTALL_EPUBCHECK=1 + runner JRE)",
    )
    @pytest.mark.asyncio
    async def test_rendered_epub_with_isbn_description_passes_epubcheck(self) -> None:
        """EPUBCheck must accept the ``urn:isbn:`` identifier form (no scheme
        attribute — the URN prefix carries the type) and dc:description. This
        is the CI-side authority for the empirically-chosen metadata mapping;
        locally (no JRE) the structural class below is the guarantee."""
        manuscript = _normalized(isbn="978-3-16-148410-0", description="A tale of lighthouses.")
        artifact = await PandocEpubRenderer().render(
            manuscript, ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            result = _run_epubcheck(artifact.path)
            assert result.returncode == 0, (
                f"EPUBCheck reported validation errors:\n"
                f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
            )
        finally:
            artifact.path.unlink(missing_ok=True)


class TestLibertinusEmbeddedAndDeclared:
    """D7: four variants embedded in EPUB/fonts/, in the OPF manifest, AND
    referenced by valid @font-face rules (the no-silent-fallback guarantee)."""

    @pytest.mark.asyncio
    async def test_four_variants_embedded_manifested_and_faced(self) -> None:
        artifact = await PandocEpubRenderer().render(
            _normalized(), ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                names = z.namelist()
                opf = _read_opf(z)
                css = _all_css(z)

            # 1. Physically embedded under EPUB/fonts/.
            font_entries = {Path(n).name for n in names if n.endswith(".otf")}
            assert len(font_entries) >= 4, f"expected >=4 embedded fonts, got {font_entries}"

            # 2. Declared in the OPF manifest (media-type font/otf).
            manifest_fonts = _manifest_font_items(opf)
            assert len(manifest_fonts) >= 4, (
                f"expected >=4 manifest font items, got {len(manifest_fonts)}"
            )

            # 3. Referenced by valid @font-face rules in the EPUB CSS.
            assert css.count("@font-face") >= 4, (
                f"expected >=4 @font-face rules, got {css.count('@font-face')}"
            )
            assert 'font-family: "Libertinus Serif"' in css
            # The body actually resolves to Libertinus (no silent fallback to a
            # pandoc/reader default like Georgia).
            assert "body {" in css and "Libertinus Serif" in css
        finally:
            artifact.path.unlink(missing_ok=True)


class TestMetadataReachesOpf:
    """title / author / language are carried into the OPF metadata block."""

    @pytest.mark.asyncio
    async def test_title_author_language_in_opf(self) -> None:
        manuscript = _normalized(
            title="The Lighthouse Years", author="Ada Quill", language=Language.DE
        )
        artifact = await PandocEpubRenderer().render(
            manuscript, ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                opf = _read_opf(z)

            title = opf.find(".//dc:title", _NS)
            creator = opf.find(".//dc:creator", _NS)
            language = opf.find(".//dc:language", _NS)
            assert title is not None and title.text == "The Lighthouse Years"
            assert creator is not None and creator.text == "Ada Quill"
            assert language is not None and language.text == "de"
        finally:
            artifact.path.unlink(missing_ok=True)


class TestIsbnDescriptionReachOpf:
    """ISBN/description (IO-001 follow-up) reach the OPF as
    ``dc:identifier`` / ``dc:description`` — empirically verified against
    pandoc 3.10.1:

    - ``--metadata=identifier:urn:isbn:<ISBN>`` REPLACES pandoc's uuid default
      and stays the package ``unique-identifier`` (pandoc emits no scheme
      attribute; the URN prefix carries the type — the idiomatic EPUB3 form).
    - ``--metadata=description:…`` maps verbatim to ``<dc:description>``.
    - Unset fields keep the legacy output: uuid identifier, no description.
    """

    @pytest.mark.asyncio
    async def test_isbn_is_the_unique_identifier_in_opf(self) -> None:
        manuscript = _normalized(isbn="978-3-16-148410-0")
        artifact = await PandocEpubRenderer().render(
            manuscript, ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                opf = _read_opf(z)

            identifier = opf.find(".//dc:identifier", _NS)
            assert identifier is not None, "dc:identifier missing from OPF"
            assert identifier.text == "urn:isbn:978-3-16-148410-0"
            # The ISBN is not a side identifier — it IS the package's
            # unique-identifier (element id matches package@unique-identifier).
            assert identifier.get("id") == opf.get("unique-identifier")
        finally:
            artifact.path.unlink(missing_ok=True)

    @pytest.mark.asyncio
    async def test_no_isbn_keeps_pandoc_uuid_identifier(self) -> None:
        """Backward compat: no ISBN → pandoc's uuid default, unchanged."""
        artifact = await PandocEpubRenderer().render(
            _normalized(), ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                opf = _read_opf(z)

            identifier = opf.find(".//dc:identifier", _NS)
            assert identifier is not None
            assert identifier.text is not None
            assert identifier.text.startswith("urn:uuid:")
        finally:
            artifact.path.unlink(missing_ok=True)

    @pytest.mark.asyncio
    async def test_description_present_in_opf_when_set(self) -> None:
        manuscript = _normalized(description="A tale of lighthouses and the sea.")
        artifact = await PandocEpubRenderer().render(
            manuscript, ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                opf = _read_opf(z)

            description = opf.find(".//dc:description", _NS)
            assert description is not None, "dc:description missing from OPF"
            assert description.text == "A tale of lighthouses and the sea."
        finally:
            artifact.path.unlink(missing_ok=True)

    @pytest.mark.asyncio
    async def test_description_absent_from_opf_when_unset(self) -> None:
        artifact = await PandocEpubRenderer().render(
            _normalized(), ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            with zipfile.ZipFile(artifact.path) as z:
                opf = _read_opf(z)

            assert opf.find(".//dc:description", _NS) is None
        finally:
            artifact.path.unlink(missing_ok=True)


class TestCoverImage:
    @pytest.mark.asyncio
    async def test_cover_embedded_when_path_provided(self, tmp_path: Path) -> None:
        cover = tmp_path / "cover.png"
        cover.write_bytes(_PNG_1X1)
        opts = ExportOptions(
            format=ExportFormat.EPUB,
            epub_options=EpubOptions(cover_image_path=str(cover)),
        )
        artifact = await PandocEpubRenderer().render(_normalized(), opts)
        try:
            with zipfile.ZipFile(artifact.path) as z:
                names = z.namelist()
            # pandoc registers the cover image in EPUB/ (image entry) — at least
            # one embedded image with a cover-related media type / name.
            assert any(n.endswith(".png") for n in names), "cover PNG not embedded"
        finally:
            artifact.path.unlink(missing_ok=True)

    @pytest.mark.asyncio
    async def test_no_cover_renders_without_crash(self) -> None:
        """Absence of a cover → pandoc default (title page), never a crash."""
        artifact = await PandocEpubRenderer().render(
            _normalized(), ExportOptions(format=ExportFormat.EPUB)
        )
        try:
            assert artifact.path.is_file()
            with zipfile.ZipFile(artifact.path) as z:
                assert "mimetype" in z.namelist()
        finally:
            artifact.path.unlink(missing_ok=True)


