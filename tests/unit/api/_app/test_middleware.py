"""Unit tests for ``narrare._app.middleware`` — RequestLoggingMiddleware.

Tests that the middleware:
- Adds an ``X-Request-ID`` header to responses
- Echoes back a custom ``X-Request-ID`` when provided by the client
"""

from __future__ import annotations

from starlette.applications import Starlette
from starlette.responses import PlainTextResponse
from starlette.testclient import TestClient

from narrare._app.middleware import RequestLoggingMiddleware


async def _homepage(request: object) -> PlainTextResponse:
    """Minimal route handler for testing."""
    return PlainTextResponse("ok")


def _make_app() -> Starlette:
    """Create a minimal Starlette app with RequestLoggingMiddleware."""
    app = Starlette(routes=[])
    app.add_middleware(RequestLoggingMiddleware)
    app.add_route("/", _homepage)
    return app


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------


def test_request_logging_adds_headers() -> None:
    """Middleware adds X-Request-ID header when client doesn't provide one."""
    client = TestClient(_make_app())

    response = client.get("/")

    assert response.status_code == 200
    assert "X-Request-ID" in response.headers
    # Should be a valid UUID (generated by uuid.uuid4())
    request_id = response.headers["X-Request-ID"]
    assert len(request_id) == 36  # UUID format: xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx


def test_request_logging_uses_custom_request_id() -> None:
    """Middleware echoes back the client-provided X-Request-ID."""
    client = TestClient(_make_app())

    custom_id = "my-custom-request-id-1234"
    response = client.get("/", headers={"X-Request-ID": custom_id})

    assert response.status_code == 200
    assert response.headers["X-Request-ID"] == custom_id


def test_request_logging_passes_response_body_through() -> None:
    """Middleware does not alter the response body."""
    client = TestClient(_make_app())

    response = client.get("/")

    assert response.text == "ok"
