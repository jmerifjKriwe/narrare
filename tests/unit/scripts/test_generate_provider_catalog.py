@pytest.mark.parametrize(
    ("document", "match"),
    [
        ("[]\n", "expected a mapping"),
        ("providers: nope\n", "must be a list"),
        ("providers: []\n", "at least one provider"),
        (_catalog(_entry() + _entry()), "duplicate provider id"),
        (_catalog(_entry(extra="    mystery: 1")), "unknown field"),
        (_catalog(_entry(omit=frozenset({"requires_endpoint_selector"}))), "missing field"),
        (_catalog(_entry(override={"api_key_env": "42"})), "expected a non-empty string or null"),
        (
            _catalog(_entry(override={"pricing_default": "{ input: 1.0 }"})),
            "'output' must be a number",
        ),
        (
            _catalog(
                _entry(override={"pricing_default": "{ input: 1.0, output: 2.0, cache_read: 0.5 }"})
            ),
            "unknown rate",
        ),
        (
            _catalog(_entry(override={"fallback_models": "[]"})),
            "at least one fallback model",
        ),
        (
            _catalog(_entry(override={"pydantic_ai_extra": "nope"})),
            "not one of",
        ),
        (
            _catalog(_entry(override={"cache_policy": "sometimes"})),
            "not one of",
        ),
        (
            _catalog(_entry(override={"settings_editable": '"yes"'})),
            "expected a boolean",
        ),
        (_catalog(_entry(provider_id="Groq")), "must match"),
    ],
)
def test_load_catalog_rejects_invalid_documents(tmp_path: Path, document: str, match: str) -> None:
    catalog = tmp_path / "catalog.yaml"
    catalog.write_text(document, encoding="utf-8")

    with pytest.raises(ValueError, match=match):
        load_catalog(catalog)


