EXPECTED_HEADER = "# AUTO-GENERATED by scripts/generate_provider_catalog.py"
EXPECTED_TS_HEADER = "// AUTO-GENERATED by scripts/generate_provider_catalog.py"

REPO_ROOT = CATALOG_PATH.parents[5]


def _entry(
    *,
    provider_id: str = "test",
    override: dict[str, str] | None = None,
    omit: frozenset[str] = frozenset(),
    extra: str = "",
) -> str:
    """One catalog entry rendered as YAML, for validation-error tests."""
    fields: dict[str, str] = {
        "id": provider_id,
        "label_key": f"settings-ai.providers.{provider_id}",
        "api_key_env": "null",
        "settings_field": "null",
        "pydantic_ai_extra": "openai",
        "listing_strategy": "openai",
        "pricing_default": "{ input: 1.0, output: 2.0 }",
        "cache_policy": "automatic",
        "fallback_models": "[gpt-4o]",
        "settings_editable": "true",
        "requires_endpoint_selector": "false",
    }
    fields.update(override or {})
    lines = [f"    {key}: {value}" for key, value in fields.items() if key not in omit]
    document = "  - " + lines[0].lstrip() + "\n" + "\n".join(lines[1:])
    if extra:
        document += "\n" + extra
    return document + "\n"


def _catalog(document: str) -> str:
    return "providers:\n" + document


