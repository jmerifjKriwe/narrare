def _write_artifacts(
    monkeypatch: MonkeyPatch,
    tmp_path: Path,
    *,
    python_text: str,
    typescript_text: str,
) -> tuple[Path, Path]:
    """Point ``--check`` at temporary artifacts instead of the committed ones."""
    python_artifact = tmp_path / "catalog_generated.py"
    typescript_artifact = tmp_path / "providers.generated.ts"
    python_artifact.write_text(python_text, encoding="utf-8", newline="\n")
    typescript_artifact.write_text(typescript_text, encoding="utf-8", newline="\n")
    monkeypatch.setattr(generator, "PY_OUTPUT", python_artifact)
    monkeypatch.setattr(generator, "TS_OUTPUT", typescript_artifact)
    return python_artifact, typescript_artifact


def test_check_reports_drifted_artifact(
    monkeypatch: MonkeyPatch, tmp_path: Path, capsys: CaptureFixture[str]
) -> None:
    specs = load_catalog(CATALOG_PATH)
    rendered_python = render_python(specs)
    drifted_python = rendered_python.replace("ANTHROPIC", "ANTHROPICX", 1)
    assert drifted_python != rendered_python

    python_artifact, _ = _write_artifacts(
        monkeypatch,
        tmp_path,
        python_text=drifted_python,
        typescript_text=render_typescript(specs),
    )

    assert generator.main(["--check"]) == 1
    output = capsys.readouterr().out
    assert str(python_artifact) in output
    assert "is stale" in output


def test_check_prints_parity_violations_and_exits_one(
    monkeypatch: MonkeyPatch, tmp_path: Path, capsys: CaptureFixture[str]
) -> None:
    specs = load_catalog(CATALOG_PATH)
    _write_artifacts(
        monkeypatch,
        tmp_path,
        python_text=render_python(specs),
        typescript_text=render_typescript(specs),
    )
    violation = ParityViolation("pricing.keys", "groq: missing from DEFAULT_RATES")

    def fake_parity(_specs: list[ProviderSpec], _root: Path) -> list[ParityViolation]:
        return [violation]

    monkeypatch.setattr(generator, "check_parity", fake_parity)

    assert generator.main(["--check"]) == 1
    assert "pricing.keys: groq: missing from DEFAULT_RATES" in capsys.readouterr().out


def test_check_compares_artifact_bytes_not_decoded_text(
    monkeypatch: MonkeyPatch, tmp_path: Path, capsys: CaptureFixture[str]
) -> None:
    """A CRLF rewrite must fail even though ``read_text`` normalises it away."""
    specs = load_catalog(CATALOG_PATH)
    rendered_python = render_python(specs)
    crlf_python = rendered_python.replace("\n", "\r\n")

    python_artifact, _ = _write_artifacts(
        monkeypatch,
        tmp_path,
        python_text=rendered_python,
        typescript_text=render_typescript(specs),
    )
    python_artifact.write_bytes(crlf_python.encode("utf-8"))

    # Universal-newline translation makes a text comparison blind to the drift:
    assert python_artifact.read_text(encoding="utf-8") == rendered_python
    assert python_artifact.read_bytes() != rendered_python.encode("utf-8")

    assert generator.main(["--check"]) == 1
    output = capsys.readouterr().out
    assert str(python_artifact) in output
    assert "is stale" in output


def test_renderers_escape_hostile_label_keys() -> None:
    """A quote or newline in a label must not emit broken source (both languages)."""
    hostile = replace(load_catalog(CATALOG_PATH)[0], label_key='a"b\\c\n')
    escaped = '"a\\"b\\\\c\\n"'
    python_source = render_python([hostile])
    typescript_source = render_typescript([hostile])

    assert escaped in python_source
    assert escaped in typescript_source
    # Negative half: the raw unescaped value must not leak into either source.
    assert hostile.label_key not in python_source
    assert hostile.label_key not in typescript_source
