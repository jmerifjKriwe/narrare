def test_rendered_python_passes_ruff_format_and_line(tmp_path: Path) -> None:
    """The committed Python artifact is formatter- and linter-clean for real.

    A source-shape assertion cannot prove formatter cleanliness, so this test
    writes the rendered module to ``tmp_path`` and invokes ruff itself with the
    repository configuration.
    """
    rendered = render_python(load_catalog(CATALOG_PATH))
    artifact = tmp_path / "catalog_generated.py"
    artifact.write_text(rendered, encoding="utf-8", newline="\n")

    ruff = shutil.which("ruff")
    if ruff is None:
        adjacent = Path(sys.executable).with_name("ruff")
        ruff = str(adjacent) if adjacent.is_file() else None
    assert ruff is not None, (
        f"ruff is not available: neither on PATH nor beside the interpreter ({sys.executable}); "
        "the dev toolchain is missing (run `uv sync`)"
    )

    config = str(REPO_ROOT / "pyproject.toml")
    commands = (
        [ruff, "format", "--check", "--config", config, str(artifact)],
        [ruff, "check", "--no-cache", "--config", config, str(artifact)],
    )
    for command in commands:
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        assert result.returncode == 0, f"{command}: {result.stdout}{result.stderr}"


