def test_gate_failure_restores_the_mirror_to_its_pre_run_state(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _mirror(tmp_path)
    # A different routed sibling's EN prompt is a parity surface the planner
    # never reads, so planning still succeeds and the gate is the first
    # observer to reject the scaffold, after the write. (The route sibling's
    # own prompt is now the cloned template: deleting that one fails before
    # anything is written, which is a different — also loud — failure.)
    (root / BUNDLED / CATEGORY / "en" / UNREAD_MODE / "system.md").unlink()
    before = _hashes(root)

    with pytest.raises(SystemExit) as exc:
        scaffold_feature(
            "SCAFFOLD-004",
            ("core",),
            root,
            with_intent=INTENT,
            category=CATEGORY,
            mode=MODE,
        )

    assert exc.value.code == GATE_FAILURE_EXIT
    assert _hashes(root) == before
    stderr = capsys.readouterr().err
    assert "intent parity gate rejected the scaffold" in stderr
    assert "missing prompt template" in stderr
    assert "restored" in stderr


def test_repository_root_runs_each_scoped_check_exactly_once(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    root = _mirror(tmp_path)
    calls: list[tuple[str, Path]] = []

    def fake_run(script: str, run_root: Path) -> subprocess.CompletedProcess[str]:
        calls.append((script, run_root))
        return subprocess.CompletedProcess([script], 0, "", "")

    # `_ROOT` is what the post-condition compares against, so patching it makes
    # the mirror the repository root without writing into the real tree.
    monkeypatch.setattr(scaffolder, "_ROOT", root)
    monkeypatch.setattr(scaffolder, "_run_check", fake_run)

    scaffold_feature("SCAFFOLD-006", ("core",), root)

    assert [script for script, _ in calls] == [
        "scripts/check_prompt_structure.py",
        "scripts/check_prompt_surface_contract.py",
        "scripts/check_locale_sync.py",
        "scripts/check_feature_path_accuracy.py",
    ]
    assert all(run_root == root for _, run_root in calls)


def test_scoped_check_failure_exits_2_naming_the_surface_and_restores(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _mirror(tmp_path)
    before = _hashes(root)

    def fake_run(script: str, run_root: Path) -> subprocess.CompletedProcess[str]:
        if script.endswith("check_locale_sync.py"):
            return subprocess.CompletedProcess([script], 1, "", "Drifted: 1\n")
        return subprocess.CompletedProcess([script], 0, "", "")

    monkeypatch.setattr(scaffolder, "_ROOT", root)
    monkeypatch.setattr(scaffolder, "_run_check", fake_run)

    with pytest.raises(SystemExit) as exc:
        scaffold_feature("SCAFFOLD-007", ("core",), root)

    assert exc.value.code == GATE_FAILURE_EXIT
    assert _hashes(root) == before
    stderr = capsys.readouterr().err
    assert "scripts/check_locale_sync.py failed (exit 1)" in stderr
    assert "Drifted: 1" in stderr
