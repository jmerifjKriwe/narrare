import pytest
import scripts.scaffold_feature as scaffolder
from scripts.check_intent_parity import collect_facts, find_disagreements
from scripts.scaffold_feature import EXISTING_ID_EXIT, GATE_FAILURE_EXIT, main, scaffold_feature

LAYERS = ("core", "api", "web")

REPO_ROOT = Path(__file__).resolve().parents[3]
CORE = Path("packages/core/narrare_core")
BUNDLED = CORE / "prompts" / "_bundled"

SURFACE_FILES = (
    CORE / "llm" / "intents" / "_enums.py",
    CORE / "llm" / "intent_categories.py",
    CORE / "llm" / "intent_profiles.py",
    CORE / "prompts" / "route_table.py",
    CORE / "prompts" / "route_table_intents.py",
    Path("scripts/architecture/prompt-surface-manifest.yaml"),
    Path("scripts/architecture/adoption-registry.yaml"),
)

CATEGORY = "kb"  # Has a routed sibling (KB_IMPROVE) and a bundled prompt family.
SIBLING_MODE = "improve"  # KB_IMPROVE's bundled prompt mode (the cloned template).
UNREAD_MODE = "extract"  # KB_EXTRACT's prompt: a parity surface the planner never reads.
MODE = "mirror_mode"
INTENT = "mirror_probe"


def _mirror(tmp_path: Path) -> Path:
    """Copy the eight declaration surfaces into *tmp_path*, keeping relative paths."""
    root = tmp_path / "repo"
    for relative in SURFACE_FILES:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO_ROOT / relative, target)
    # The parity oracle checks every routed intent's prompt family, so the
    # mirror needs the whole bundled tree to stay green before the scaffold.
    shutil.copytree(REPO_ROOT / BUNDLED, root / BUNDLED)
    return root


def _hashes(root: Path) -> dict[str, str]:
    return {
        path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in root.rglob("*")
        if path.is_file()
    }


def test_with_intent_writes_all_eight_surfaces_and_parity_gate_is_green(
    tmp_path: Path,
) -> None:
    root = _mirror(tmp_path)
    written = scaffold_feature(
        "SCAFFOLD-001",
        ("core",),
        root,
        with_intent=INTENT,
        category=CATEGORY,
        mode=MODE,
    )
    rel = {path.relative_to(root).as_posix() for path in written}

    assert {relative.as_posix() for relative in SURFACE_FILES} <= rel
    for locale in ("en", "de", "fr"):
        assert (BUNDLED / CATEGORY / locale / MODE / "system.md").as_posix() in rel

    assert 'MIRROR_PROBE = "mirror_probe"' in (root / SURFACE_FILES[0]).read_text()
    assert "LLMIntent.MIRROR_PROBE: IntentCategory.KB" in (root / SURFACE_FILES[1]).read_text()
    assert "LLMIntent.MIRROR_PROBE: IntentProfile(" in (root / SURFACE_FILES[2]).read_text()
    assert (
        'LLMIntent.MIRROR_PROBE: PromptRouteConfig("kb", "mirror_mode"'
        in (root / SURFACE_FILES[3]).read_text()
    )
    route_intents = (root / SURFACE_FILES[4]).read_text()
    assert 'LLMIntent.MIRROR_PROBE: "kb"' in route_intents
    assert 'LLMIntent.MIRROR_PROBE: "mirror_mode"' in route_intents
    assert "  - intent: MIRROR_PROBE" in (root / SURFACE_FILES[5]).read_text()
    assert f"  {CATEGORY}/{MODE}: true" in (root / SURFACE_FILES[6]).read_text()

    prompt = root / BUNDLED / CATEGORY / "de" / MODE / "system.md"
    text = prompt.read_text()
    assert "prompt_type: kb" in text
    assert "prompt_language: de" in text
    assert "## System Prompt" in text
    assert "Generated by scripts/scaffold_feature.py" in text

    # The body is cloned from the routed sibling's prompt, not re-derived: the
    # structure gate's sections, variables and XML wrapper all survive.
    assert (root / BUNDLED / CATEGORY / "en" / SIBLING_MODE / "system.md").is_file()
    for heading in (
        "### Context",
        "#### Current Entry Content",
        "### Output Format",
        "### Do NOT",
    ):
        assert heading in text
    assert "{{world_context}}" in text
    assert "<user_provided_text>{{entry_content}}</user_provided_text>" in text

    for path in written:
        assert "TODO" not in path.read_text(encoding="utf-8")

    # Acceptance criterion: the committed parity gate accepts the mirror.
    assert find_disagreements(collect_facts(root)) == []


def test_second_scaffold_with_same_intent_exits_1_and_leaves_files_untouched(
    tmp_path: Path,
) -> None:
    root = _mirror(tmp_path)
    scaffold_feature(
        "SCAFFOLD-001", ("core",), root, with_intent=INTENT, category=CATEGORY, mode=MODE
    )
    before = _hashes(root)

    with pytest.raises(SystemExit) as exc:
        scaffold_feature(
            "SCAFFOLD-002", ("core",), root, with_intent=INTENT, category=CATEGORY, mode=MODE
        )

    assert exc.value.code == EXISTING_ID_EXIT
    assert _hashes(root) == before


@pytest.mark.parametrize("flag", ["--category", "--mode"])
def test_with_intent_without_category_or_mode_exits_2_and_writes_nothing(
    tmp_path: Path, flag: str, capsys: pytest.CaptureFixture[str]
) -> None:
    arguments = ["SCAFFOLD-003", "core", "--with-intent", "probe", "--root", str(tmp_path)]
    arguments += ["--category", "kb"] if flag == "--mode" else ["--mode", "probe"]

    with pytest.raises(SystemExit) as exc:
        main(arguments)

    assert exc.value.code == GATE_FAILURE_EXIT
    stderr = capsys.readouterr().err
    assert "--category" in stderr
    assert "--mode" in stderr
    assert not list(tmp_path.iterdir())


